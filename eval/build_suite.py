"""Generate the EvalForge suite: every system classifies the same 770 test messages.

    python eval/build_suite.py               # all five systems (Claude ones need ANTHROPIC_API_KEY)
    python eval/build_suite.py --local-only  # TF-IDF and the fine-tuned model only (free)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from ftvp import data  # noqa: E402
from ftvp.cli import SYSTEMS  # noqa: E402

LOCAL = ["tfidf", "finetuned"]


def build(local_only: bool = False) -> dict:
    names = LOCAL if local_only else list(SYSTEMS)
    providers = [{"id": name, "provider": "python", "model": "ftvp.systems:classify", "params": SYSTEMS[name]}
                 for name in names]
    cases = [{"id": f"s{i:03d}", "tags": [ex.label], "vars": {"text": ex.text}, "expected": ex.label,
              "checks": [{"type": "exact", "name": "correct"}]}
             for i, ex in enumerate(data.eval_subset())]
    return {
        "name": "Banking77 intent classification: fine-tuned vs. prompted",
        "description": "Generated by eval/build_suite.py. 770 test messages, 10 per intent.",
        "providers": providers,
        "prompts": [{"id": "message", "template": "{text}"}],
        "cases": cases,
    }


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--local-only", action="store_true")
    p.add_argument("--out")
    args = p.parse_args()
    out = Path(args.out or ROOT / "eval" / ("suite_local.yaml" if args.local_only else "suite.yaml"))
    out.write_text("# Generated by eval/build_suite.py. Do not edit by hand.\n" +
                   yaml.safe_dump(build(args.local_only), sort_keys=False, width=200, allow_unicode=True))
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
